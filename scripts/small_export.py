"""Compact C99 float trees: 9 bytes/node in separate read-only arrays, no heap."""
from __future__ import annotations

import json
import subprocess
import tempfile
from pathlib import Path

import numpy as np


def threshold32(value):
    # sklearn RF compares float32 inputs to float64 thresholds. Round downward
    # to preserve <= exactly on the float32 grid, including boundary values.
    result = np.float32(value)
    if float(result) > value:
        result = np.nextafter(result, np.float32(-np.inf))
    return float(result)


def emit(model, name, n_features):
    values, left, right, features, roots = [], [], [], [], []
    boosted = hasattr(model, '_predictors')
    trees = [stage[0].nodes for stage in model._predictors] if boosted else [t.tree_ for t in model.estimators_]
    for tree in trees:
        offset = len(values)
        roots.append(offset)
        count = len(tree) if boosted else tree.node_count
        for i in range(count):
            leaf = bool(tree[i]['is_leaf']) if boosted else tree.children_left[i] == -1
            feature = int(tree[i]['feature_idx']) if boosted else int(tree.feature[i])
            if leaf:
                value = float(tree[i]['value']) if boosted else float(tree.value[i, 0, 1])
                l = r = 0
            else:
                value = threshold32(float(tree[i]['num_threshold']) if boosted else float(tree.threshold[i]))
                l = offset + int(tree[i]['left'] if boosted else tree.children_left[i])
                r = offset + int(tree[i]['right'] if boosted else tree.children_right[i])
            values.append(value); left.append(l); right.append(r); features.append(255 if leaf else feature)
    assert len(values) < 65536, 'uint16 node indices overflow'
    assert n_features < 255
    def f(value):
        return float(np.float32(value)).hex() + 'f'
    def array(ctype, label, items):
        return f'static const {ctype} {label}[{len(items)}] = {{\n' + ',\n'.join(','.join(items[i:i+12]) for i in range(0, len(items), 12)) + '\n};\n'
    header = (f'#ifndef {name.upper()}_H\n#define {name.upper()}_H\n'
              '#ifdef __cplusplus\nextern "C" {\n#endif\n'
              f'/* Stat-major float features; returns P(series-label 1: wrong), or -1 for nonfinite input.\n'
              '   Repetitions have series-level labels only; average probabilities over the set. */\n'
              f'float {name}_predict(const float x[{n_features}]);\n'
              '#ifdef __cplusplus\n}\n#endif\n#endif\n')
    source = f'/* Generated by scripts/train_small.py; do not edit arrays. */\n#include "{name}.h"\n#include <stdint.h>\n#include <float.h>\n'
    if boosted:
        source += '#include <math.h>\n'
    source += array('float', 'value', [f(v) for v in values])
    source += array('uint16_t', 'left', [str(v) for v in left])
    source += array('uint16_t', 'right', [str(v) for v in right])
    source += array('uint8_t', 'feature', [str(v) for v in features])
    source += array('uint16_t', 'root', [str(v) for v in roots])
    initial = float(model._baseline_prediction[0, 0]) if boosted else 0.
    source += (f'float {name}_predict(const float x[{n_features}]) {{\n'
               f'    float sum = {f(initial)};\n'
               f'    for (unsigned j = 0; j < {n_features}; ++j)\n'
               '        if (x[j] != x[j] || x[j] > FLT_MAX || x[j] < -FLT_MAX) return -1.0f;\n'
               f'    for (unsigned t = 0; t < {len(roots)}; ++t) {{\n'
               '        uint16_t i = root[t];\n'
               '        while (feature[i] != 255) i = x[feature[i]] <= value[i] ? left[i] : right[i];\n'
               '        sum += value[i];\n    }\n')
    source += ('    return 1.0f / (1.0f + expf(-sum));\n}\n' if boosted else f'    return sum / {f(len(roots))};\n}}\n')
    return source, header, {'nodes': len(values), 'trees': len(roots), 'array_bytes': 9*len(values)+2*len(roots),
                            'threshold_storage': 'float32, rounded downward on float32 grid',
                            'probability_quantisation': 'float32; no integer quantisation'}


def object_sizes(sources):
    """Compile before publishing anything; target code+rodata must fit together."""
    result = {}
    with tempfile.TemporaryDirectory(prefix='small-budget-') as directory:
        temp = Path(directory)
        # Declaration only for freestanding Clang; board link resolves real expf.
        (temp/'math.h').write_text('float expf(float);\n')
        for name, (source, header, _) in sources.items():
            (temp/f'{name}.c').write_text(source)
            (temp/f'{name}.h').write_text(header)
            obj = temp/f'{name}.o'
            command = ['clang', '--target=arm-none-eabi', '-mcpu=cortex-m4', '-mthumb', '-mfpu=fpv4-sp-d16',
                       '-mfloat-abi=hard', '-Oz', '-std=c99', '-ffreestanding', '-fno-builtin',
                       '-fdata-sections', '-ffunction-sections', '-I', str(temp), '-c', str(temp/f'{name}.c'), '-o', str(obj)]
            subprocess.run(command, check=True)
            output = subprocess.check_output(['llvm-size', '-A', str(obj)], text=True)
            sections = {}
            for line in output.splitlines():
                fields = line.split()
                if len(fields) == 3 and fields[0].startswith('.') and fields[1].isdigit():
                    sections[fields[0]] = int(fields[1])
            result[name] = {'text': sum(v for k, v in sections.items() if k.startswith('.text')),
                            'rodata': sum(v for k, v in sections.items() if k.startswith('.rodata')),
                            'data': sum(v for k, v in sections.items() if k.startswith('.data')),
                            'bss': sum(v for k, v in sections.items() if k.startswith('.bss')),
                            'exidx': sum(v for k, v in sections.items() if k.startswith('.ARM.exidx')),
                            'sections': sections}
    return result


def check_budget(sources, budget_bytes=120000, node_budget=10000):
    sizes = object_sizes(sources)
    nodes = sum(v[2]['nodes'] for v in sources.values())
    # Include exception index sections too; unresolved libc/libm is a linked-probe concern.
    total = sum(s['text']+s['rodata']+s['exidx'] for s in sizes.values())
    if nodes > node_budget or total > budget_bytes:
        raise ValueError(f'model budget overflow: {nodes}/{node_budget} nodes, {total}/{budget_bytes} object bytes; no exports written')
    return {'combined_object_bytes': total, 'node_count': nodes, 'node_budget': node_budget,
            'budget_bytes': budget_bytes, 'models': sizes,
            'scope': 'object sizes, not linked flash; code, arrays and exception indices; expf unresolved if used'}
